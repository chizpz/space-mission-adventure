const SPOKEN = { "LANSA": 2 };

function syllables(word) {
  const clean = word.replace(/[.,!?:]/g, "");
  if (SPOKEN[clean] !== undefined) return SPOKEN[clean];
  const v = clean.match(/[АЕЁИОУЫЭЮЯAEIOU]/gi);
  return v ? v.length : 0;
}

function buildChunks() {
  const chunks = [];
  for (const [s, e, lines, kind] of SEGMENTS) {
    const words = [];
    lines.forEach((line, li) => {
      line.split(" ").forEach((tok) => {
        let color = null, txt = tok;
        const m = tok.match(/^([ryk]):(.*)$/);
        if (m) { color = m[1]; txt = m[2]; }
        words.push({ txt, color, line: li, w: syllables(txt) + 0.4 });
      });
    });
    const total = words.reduce((a, b) => a + b.w, 0);
    let acc = 0;
    for (const w of words) {
      w.s = s + (acc / total) * (e - s);
      acc += w.w;
      w.e = s + (acc / total) * (e - s);
    }
    lines.forEach((_, li) => {
      const ws = words.filter((w) => w.line === li);
      chunks.push({ words: ws, s: ws[0].s, e: ws[ws.length - 1].e, kind: kind || "sub" });
    });
  }
  for (let i = 0; i < chunks.length; i++) {
    const next = chunks[i + 1];
    const hold = chunks[i].e + 0.35;
    chunks[i].show = chunks[i].s - 0.06;
    chunks[i].hide = next && next.s - 0.06 < hold + 0.25 ? next.s - 0.06 : hold;
  }
  return chunks;
}

